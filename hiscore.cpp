static const char* HISCORE_PATH = "HiScores.PAR";

bool LoadHiScores(uint8_t table[HISCORE_FILE_SIZE])
{
    memcpy(table, DEFAULT_HISCORES, HISCORE_FILE_SIZE);
    FILE* f = fopen(HISCORE_PATH, "rb");
    if (!f) {
        // 352f: create the file with the default table.
        if (!SaveHiScores(table)) {
            printf("WARNING: CAN'T CREATE %s; HIGH SCORES WON'T BE KEPT\n", HISCORE_PATH);
            return false;
        }
        return true;
    }
    uint8_t data[HISCORE_FILE_SIZE];
    bool ok = fread(data, 1, HISCORE_FILE_SIZE, f) == HISCORE_FILE_SIZE;
    fclose(f);
    if (!ok) {
        printf("WARNING: %s IS TOO SHORT; USING THE DEFAULT HIGH SCORES\n", HISCORE_PATH);
        return false;
    }
    memcpy(table, data, HISCORE_FILE_SIZE);
    return true;
}

bool SaveHiScores(const uint8_t table[HISCORE_FILE_SIZE])
{
    FILE* f = fopen(HISCORE_PATH, "wb");
    if (!f)
        return false;
    bool ok = fwrite(table, 1, HISCORE_FILE_SIZE, f) == HISCORE_FILE_SIZE;
    return fclose(f) == 0 && ok;
}
